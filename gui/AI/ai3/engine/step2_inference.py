HERE = os.path.dirname(os.path.abspath(__file__))
# Vendored into naksha-lidar: the Myria3D clone now ships beside this file, and the model
# files are vendored, so this path is resolved relative to the module rather than to the
# current working directory.
MYRIA3D_DIR = os.path.join(HERE, "myria3d")
SEED = 42
HF_BASE = "https://huggingface.co/IGNF/FRACTAL-LidarHD_7cl_randlanet/resolve/main"
# The filename in the original task spec (20230930_..._Myria3DV3.4.0.ckpt) does not exist on the hub.
CHECKPOINT_URL = f"{HF_BASE}/FRACTAL-LidarHD_7cl_randlanet.ckpt"
CONFIG_URL = f"{HF_BASE}/FRACTAL-LidarHD_7cl_randlanet-inference-Myria3DV3.8.yaml"
CHECKPOINT_PATH = os.path.join(HERE, "models", "fractal_lidarhd_myria3d.ckpt")
CONFIG_PATH = os.path.join(HERE, "models", "inference_config.yaml")
# MYRIA3D_DIR is defined above: clone of IGNF/myria3d at tag V3.8.2, vendored beside this file.

# Myria3D seeds RNGs only in its training entry point (train.py calls seed_everything), while
# the predict path decimates points with torch.randperm() in pyg_randla_net.py. An unseeded
# predict process therefore subsamples a different subset on every run, which moves whole
# classes around (bridge counts swung 1 to 368 on identical input). This shim pins the RNGs
# and the kernel choices, then hands over to run.py unchanged.
_CHILD_SHIM = '''"""Generated by step2_inference.py - seeds RNGs before Myria3D's predict path runs."""
import os
import random
import sys

import numpy as np
import torch

SEED = {seed}
random.seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)
if torch.cuda.is_available():
    torch.cuda.manual_seed_all(SEED)
torch.backends.cudnn.deterministic = True
torch.backends.cudnn.benchmark = False
# Deterministic CUDA kernels make the model's scatter-adds slow (about 40 % of the inference on a
# small GPU). By default they are off: every random choice is still seeded, only the float
# summation order may differ, and on FUNIVIA (3.6 M points) the classes came out identical, run
# after run. NAKSHA_AI3_DETERMINISTIC=1 restores bit-exact kernels.
if os.environ.get("NAKSHA_AI3_DETERMINISTIC") == "1":
    try:
        torch.use_deterministic_algorithms(True, warn_only=True)
    except AttributeError:  # older torch without the switch
        pass
print("[shim] torch", torch.__version__, "| seed", SEED,
      "| cudnn.deterministic", torch.backends.cudnn.deterministic,
      "| CUBLAS_WORKSPACE_CONFIG", os.environ.get("CUBLAS_WORKSPACE_CONFIG"))

# `python run.py` puts the script's directory on sys.path; runpy does not, so the myria3d
# package would not be importable without this.
MYRIA3D_DIR = {repo!r}
if MYRIA3D_DIR not in sys.path:
    sys.path.insert(0, MYRIA3D_DIR)
os.chdir(MYRIA3D_DIR)

sys.argv[0] = "run.py"
import runpy

runpy.run_path("run.py", run_name="__main__")
'''


def enforce_determinism(seed: int = SEED, report: bool = True) -> None:
    """Pin every RNG and kernel choice PyTorch exposes, in this process."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    try:
        torch.use_deterministic_algorithms(True, warn_only=True)
    except AttributeError:
        pass
    if report:
        print(f"[*] Enforcing PyTorch/CUDA Determinism (Seed: {seed})...")
        print(f"    - CUDNN Deterministic: {torch.backends.cudnn.deterministic}")
        print(f"    - Workspace Config   : {os.environ.get('CUBLAS_WORKSPACE_CONFIG')}")


def _write_child_shim(work_dir: str, seed: int) -> str:
    """Write the child-process seeding shim and return its absolute path."""
    path = os.path.abspath(os.path.join(work_dir, "_myria3d_deterministic.py"))
    with open(path, "w", encoding="utf-8") as f:
        f.write(_CHILD_SHIM.format(seed=seed, repo=os.path.abspath(MYRIA3D_DIR)))
    return path


def _download(url: str, dest: str):
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    print(f"[Step 2] Downloading {os.path.basename(dest)} ...")
    urllib.request.urlretrieve(url, dest)


def ensure_model_files():
    # The Naksha engine is fully offline: the checkpoint and config are vendored beside this
    # module. Downloading them is only a development convenience, and it must never happen on
    # an operator's machine, so it is opt-in through NAKSHA_AI3_ALLOW_MODEL_DOWNLOAD.
    if not os.path.exists(CHECKPOINT_PATH) and \
            os.environ.get("NAKSHA_AI3_ALLOW_MODEL_DOWNLOAD") != "1":
        raise RuntimeError(
            f"Model checkpoint missing: {CHECKPOINT_PATH}\n"
            "The vendored engine is offline and never downloads model files. "
            "Restore the file, or set NAKSHA_AI3_ALLOW_MODEL_DOWNLOAD=1 to fetch it from "
            f"{CHECKPOINT_URL}")
    if not os.path.exists(CHECKPOINT_PATH):
        _download(CHECKPOINT_URL, CHECKPOINT_PATH)
    if not os.path.exists(CONFIG_PATH):
        _download(CONFIG_URL, CONFIG_PATH)
        # The Comet logger needs credentials and is not used for inference
        import re
        with open(CONFIG_PATH, encoding="utf-8") as f:
            text = f.read()
        text = re.sub(r"(?ms)^logger:.*?(?=^task:)", "logger: {}\n", text)
        with open(CONFIG_PATH, "w", encoding="utf-8") as f:
            f.write(text)


COLOR_DIMS = {"Red": "red", "Green": "green", "Blue": "blue", "Infrared": "nir"}  # PDAL name -> laspy name
NEUTRAL_FILL = 32768  # mid-range 16-bit; Myria3D divides colours by 255*256, so this feeds ~0.5
HAG_DIM = "HeightAboveGround=float32"


def missing_color_dims(src: str):
    """PDAL names of colour/NIR channels that are absent or all-zero in the input."""
    with laspy.open(src) as f:
        names = set(f.header.point_format.dimension_names)
        present = {pdal_n for pdal_n, las_n in COLOR_DIMS.items() if las_n in names}
        nonzero = set()
        for chunk in f.chunk_iterator(2_000_000):
            for pdal_n in present - nonzero:
                if np.asarray(chunk[COLOR_DIMS[pdal_n]]).max() > 0:
                    nonzero.add(pdal_n)
            if nonzero == present:
                break
    return [d for d in COLOR_DIMS if d not in nonzero], present


def _raster_info(path: str):
    from osgeo import gdal
    ds = gdal.Open(path)
    if ds is None:
        raise ValueError(f"[X] Cannot open orthophoto: {path}")
    band_type = gdal.GetDataTypeName(ds.GetRasterBand(1).DataType)
    return ds.RasterCount, band_type


def prepare_model_input(src: str, dst: str, orthophoto: str = None, allow_neutral_fill: bool = True):
    """Write `dst` as LAS 1.4 point format 8 with valid Red/Green/Blue/Infrared.

    1. Colours already in the file are kept.
    2. Missing ones are projected from `orthophoto` (bands 1-4 = R,G,B,NIR, as in NAIP;
       8-bit imagery is scaled to the 16-bit range Myria3D expects).
    3. Anything still missing gets a neutral mid-range fill, because no colourless
       checkpoint is published for FRACTAL-LidarHD. Constant channels carry no
       information, so predictions on such data remain unreliable.
    Returns the list of channels that were filled with the neutral constant."""
    missing, present = missing_color_dims(src)
    stages = [{"type": "readers.las", "filename": src, "extra_dims": HAG_DIM}]

    if missing and orthophoto:
        n_bands, band_type = _raster_info(orthophoto)
        scale = 256.0 if band_type == "Byte" else 1.0
        wanted = {"Red": 1, "Green": 2, "Blue": 3, "Infrared": 4}
        dims = [f"{d}:{wanted[d]}:{scale}" for d in missing if wanted[d] <= n_bands]
        print(f"        Colorizing from orthophoto ({n_bands} bands, {band_type}): {[d.split(':')[0] for d in dims]}")
        # filters.colorization needs the target dimensions to exist
        create = [f"=>{d.split(':')[0]}" for d in dims if d.split(":")[0] not in present]
        if create:
            stages.append({"type": "filters.ferry", "dimensions": ", ".join(create)})
        stages.append({"type": "filters.colorization", "raster": orthophoto, "dimensions": ", ".join(dims)})
        missing = [d for d in missing if wanted[d] > n_bands]

    if missing:
        if not allow_neutral_fill:
            raise ValueError(f"[X] Missing colour channels {missing} and neutral fill disabled")
        create = [f"=>{d}" for d in missing if d not in present]
        if create:
            stages.append({"type": "filters.ferry", "dimensions": ", ".join(create)})
        stages.append({"type": "filters.assign",
                       "assignment": [f"{d}[:]={NEUTRAL_FILL}" for d in missing]})

    stages.append({"type": "writers.las", "filename": dst, "forward": "all",
                   "extra_dims": HAG_DIM, "minor_version": 4, "dataformat_id": 8})
    pdal.Pipeline(json.dumps(stages)).execute()
    return missing


def run_step2_inference(input_normalized_laz: str, output_ai_laz: str, orthophoto: str = None,
                        work_dir: str = None, seed: int = SEED):
    """Run Myria3D inference. ``work_dir`` isolates the scratch files (the caller can point it
    inside its own run folder); it defaults to ``output_temp`` beside this module."""
    print(f"[Step 2] Starting AI Inference Engine on: {input_normalized_laz}")
    start_time = time.time()
    enforce_determinism(seed)

    # 1. Hardware check
    use_gpu = torch.cuda.is_available()
    if use_gpu:
        print(f"        [OK] Target GPU: {torch.cuda.get_device_name(0)} (CUDA active)")
    else:
        print(f"        [!] CUDA GPU not available to PyTorch ({torch.__version__}); running on CPU (slow).")

    # 2. Checkpoint + config
    ensure_model_files()

    # 3. Prepare the input (colour channels) in a scratch folder
    work_dir = work_dir or os.path.join(HERE, "output_temp")
    shutil.rmtree(work_dir, ignore_errors=True)
    os.makedirs(work_dir)
    shim_path = _write_child_shim(work_dir, seed)
    prepared = os.path.join(work_dir, "model_input.las")
    filled = prepare_model_input(input_normalized_laz, prepared, orthophoto)
    if filled:
        print(f"        [!] No real data for {filled}; filled with neutral {NEUTRAL_FILL}. "
              "Predictions will be unreliable - supply --orthophoto or a coloured LAZ.")
    else:
        print("        [OK] RGB/NIR available for inference.")

    def q(path):  # Hydra override values with spaces must be quoted
        return "'" + os.path.abspath(path).replace("\\", "/") + "'"

    # 4. Myria3D inference (no `myria3d predict` CLI exists; run.py is the entry point)
    print("        Streaming tile inference through Myria3D engine...")
    cmd = [
        sys.executable, shim_path,   # seeds RNGs, then runs ./run.py through runpy
        "--config-path", os.path.dirname(CONFIG_PATH),
        "--config-name", os.path.splitext(os.path.basename(CONFIG_PATH))[0],
        "task.task_name=predict",
        "datamodule.num_workers=0",  # worker processes cannot be spawned on Windows
        f"predict.src_las={q(prepared)}",
        f"predict.output_dir={q(work_dir)}",
        f"predict.ckpt_path={q(CHECKPOINT_PATH)}",
        f"predict.gpus={1 if use_gpu else 0}",
        f"hydra.run.dir={q(os.path.join(work_dir, 'hydra'))}",
    ]
    env = os.environ.copy()
    # Myria3D shells out to the `pdal` CLI from the conda env
    env["PATH"] = os.path.join(sys.base_prefix, "Library", "bin") + os.pathsep + env.get("PATH", "")
    env.update(DETERMINISM_ENV)   # effective in the child, unlike in-process setdefault
    result = subprocess.run(cmd, cwd=MYRIA3D_DIR, env=env)
    if result.returncode != 0:
        raise RuntimeError("Myria3D inference failed (see log above)")

    # Myria3D rewrites the cloud and drops custom extra dims, so restore
    # HeightAboveGround from the (point-for-point identical) input.
    produced = os.path.join(work_dir, os.path.basename(prepared))
    pred = laspy.read(produced)
    src = laspy.read(prepared)
    if len(pred.points) != len(src.points) or not (
        np.array_equal(pred.X, src.X) and np.array_equal(pred.Y, src.Y)
    ):
        raise ValueError("[X] Predicted cloud is not point-aligned with the input")
    if "HeightAboveGround" not in pred.point_format.dimension_names:
        pred.add_extra_dim(laspy.ExtraBytesParams(name="HeightAboveGround", type=np.float32))
    pred.HeightAboveGround = src.HeightAboveGround
    # Myria3D keeps the input Classification and writes its output to the
    # PredictedClassification extra dim; put the model output into Classification.
    # FRACTAL codes: 1 unclassified, 2 ground, 5 vegetation, 6 building, 9 water,
    # 17 bridge, 64 lasting_above. Vegetation -> 3 (general, split by height in Step 3);
    # lasting_above has no ASPRS equivalent -> 1.
    model_out = np.asarray(pred.PredictedClassification).astype(np.uint8)
    model_out[model_out == 5] = 3
    model_out[model_out == 64] = 1
    pred.classification = model_out
    if os.path.exists(output_ai_laz):
        os.remove(output_ai_laz)
    pred.write(output_ai_laz)
    del pred, src
    shutil.rmtree(work_dir, ignore_errors=True)

    elapsed = time.time() - start_time
    print(f"        Inference completed in {elapsed:.2f} seconds.")

    # 5. Validation & class summary
    print("        Validating output class predictions...")
    with laspy.open(input_normalized_laz) as f:
        expected = f.header.point_count
    las = laspy.read(output_ai_laz)
    total = len(las.points)
    if total != expected:
        raise ValueError(f"[X] Point count mismatch: expected {expected:,}, got {total:,}")
    if "HeightAboveGround" not in las.point_format.dimension_names:
        raise ValueError("[X] HeightAboveGround dimension was lost")
    print(f"        [OK] All {total:,} points present; HeightAboveGround preserved.")

    classes, counts = np.unique(np.asarray(las.classification), return_counts=True)
    print("\n        --- AI Base Predictions Summary ---")
    for c, cnt in zip(classes, counts):
        print(f"        - Class {c:2d}: {cnt:10,d} pts ({cnt / total * 100:6.2f}%)")
    print("        ------------------------------------")
    print(f"[Step 2] Done -> {output_ai_laz}\n")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="Step 2: Myria3D inference")
    ap.add_argument("input", nargs="?", default="normalized_temp.laz")
    ap.add_argument("output", nargs="?", default="ai_predicted.laz")
    ap.add_argument("--orthophoto", help="GeoTIFF (NAIP-style R,G,B,NIR bands) used to colour the cloud when it has no RGB/NIR")
    a = ap.parse_args()
    run_step2_inference(a.input, a.output, a.orthophoto)
