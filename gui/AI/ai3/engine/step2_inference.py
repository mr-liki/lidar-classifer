# Determinism must be pinned before torch/CUDA are imported: cuBLAS reads
# CUBLAS_WORKSPACE_CONFIG when it creates its first handle, and hash randomisation is fixed
# at interpreter start. These values are also handed to the inference subprocess (Step 2 runs
# Myria3D in a child process, so seeds set here would not otherwise reach it).
import os

DETERMINISM_ENV = {
    "CUBLAS_WORKSPACE_CONFIG": ":4096:8",
    "PYTHONHASHSEED": "42",
    "NVIDIA_TF32_OVERRIDE": "0",   # TF32 changes numerics versus true fp32
}
for _key, _value in DETERMINISM_ENV.items():
    os.environ.setdefault(_key, _value)

